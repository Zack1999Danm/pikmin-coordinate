-- Pikmin coordinate directory: database + access control
create extension if not exists pgcrypto;

create table if not exists public.stores (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.site_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.stores enable row level security;
alter table public.site_admins enable row level security;

-- Anyone can read the public directory.
drop policy if exists "Anyone can read stores" on public.stores;
create policy "Anyone can read stores"
on public.stores for select
to anon, authenticated
using (true);

-- Only user IDs explicitly inserted into site_admins can change store data.
drop policy if exists "Admins can insert stores" on public.stores;
create policy "Admins can insert stores"
on public.stores for insert
to authenticated
with check (exists (
  select 1 from public.site_admins a where a.user_id = auth.uid()
));

drop policy if exists "Admins can update stores" on public.stores;
create policy "Admins can update stores"
on public.stores for update
to authenticated
using (exists (
  select 1 from public.site_admins a where a.user_id = auth.uid()
))
with check (exists (
  select 1 from public.site_admins a where a.user_id = auth.uid()
));

drop policy if exists "Admins can delete stores" on public.stores;
create policy "Admins can delete stores"
on public.stores for delete
to authenticated
using (exists (
  select 1 from public.site_admins a where a.user_id = auth.uid()
));

-- Users can only see their own admin membership row.
drop policy if exists "Admins can read own membership" on public.site_admins;
create policy "Admins can read own membership"
on public.site_admins for select
to authenticated
using (user_id = auth.uid());

